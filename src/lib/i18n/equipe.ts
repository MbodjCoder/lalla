const DICTIONNAIRES: Record<LangueEquipe, Record<CleTexteEquipe, string>> = {
  fr,
  en,
  wo,
  es,
  it,
  de,
  pt,
  ar,
};

// Texte à deux formes « une||plusieurs » : la forme est choisie selon {n} et les règles de la langue
const SEPARATEUR_PLURIEL = "||";

export function traducteurEquipe(langue: LangueEquipe) {
  const dictionnaire = DICTIONNAIRES[langue];
  const pluriel = new Intl.PluralRules(FICHES_LANGUES[langue].locale);
  return (cle: CleTexteEquipe, variables?: Record<string, string | number>) => {
    let texte = dictionnaire[cle];
    if (texte.includes(SEPARATEUR_PLURIEL)) {
      const [une, plusieurs] = texte.split(SEPARATEUR_PLURIEL);
      const n = Number(variables?.n);
      texte = Number.isFinite(n) && pluriel.select(n) === "one" ? une : plusieurs;
    }
    return texte.replace(/\{(\w+)\}/g, (_, nom: string) => String(variables?.[nom] ?? ""));
  };
}

export type TraduireEquipe = ReturnType<typeof traducteurEquipe>;

/** Les deux formes d'un texte pluriel, {n} conservé : pour un composant client qui ne connaît n qu'à l'affichage. */
export function formesPluriel(langue: LangueEquipe, cle: CleTexteEquipe) {
  const [une, plusieurs = une] = DICTIONNAIRES[langue][cle].split(SEPARATEUR_PLURIEL);
  return { une, plusieurs };
}

